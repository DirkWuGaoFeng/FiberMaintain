class DataCollectorState(TypedDict):
    """Data collector sub-graph state (ReAct Agent + ToolNode)."""

    messages: Annotated[list[BaseMessage], add_messages]
    fiber_ids: list[int]
    query_type: str
    results: dict
    errors: list[str]
    retry_count: int


class BatchChunkState(TypedDict):
    """Single chunk state for Send dispatch unit."""

    chunk_id: str
    fiber_ids: list[int]  # <= 50 per chunk
    chunk_index: int
    result: Optional[dict]
    error: Optional[str]
    idempotency_key: str


class ProactiveState(TypedDict):
    """Proactive diagnosis sub-graph state (event-triggered, no user interaction)."""

    event: dict
    fiber_id: Optional[int]
    collected_data: Optional[str]
    analysis: Optional[str]
    alert_message: Optional[str]
    timeout_exceeded: bool


