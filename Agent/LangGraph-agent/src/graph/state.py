def create_initial_state(user_message: str, thread_id: str = "") -> dict:
    """
    Create initial state for a new conversation turn.

    Args:
        user_message: The user's input text
        thread_id: Conversation thread ID (auto-generated if empty)

    Returns:
        Complete initial state dict matching MainGraphState schema
    """
    from ..config import MAX_LLM_CALLS, MAX_LOOPS

    # Generate trace_id for request-level tracking
    trace_id = uuid.uuid4().hex[:12]

    return {
        "messages": [HumanMessage(content=user_message)],
        "thread_id": thread_id or uuid.uuid4().hex[:12],
        "user_input": user_message,
        # Rule engine
        "rule_match": None,
        "fast_path_result": None,
        # Intent & params
        "intent": None,
        "intent_result": None,
        "raw_extractions": None,
        "normalized_params": None,
        # Loop control
        "loop_count": 0,
        "max_loops": MAX_LOOPS,
        "llm_call_count": 0,
        "max_llm_calls": MAX_LLM_CALLS,
        "no_progress_count": 0,
        "last_action_signature": None,
        "loop_history": [],
        # Data
        "collected_data_summary": None,
        "rule_judgment": None,
        "analysis_verdict": None,
        # Narrator [v7.1]
        "narration": None,
        "narrator_validation_passed": None,
        # Report
        "report_content": None,
        "report_eval": None,
        # Batch
        "batch_chunks": [],
        "batch_results": [],
        "batch_progress": {},
        # Knowledge
        "rag_context": [],
        # Degradation
        "degradation_level": 0,
        # Output
        "final_output": None,
        "processing_path": "normal",
        # Audit
        "request_id": uuid.uuid4().hex[:16],
        "audit_trail": [],
        # Metadata
        "token_budget_remaining": 10000,
        "session_start_time": datetime.now().isoformat(),
        # Tracing [v7.1]
        "trace_id": trace_id,
    }
